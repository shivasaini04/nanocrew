"""Generate extension/probes.generated.js from the Python that already owns these scripts.

MV3's extension CSP forbids building a function from a string, even in the isolated world
(measured 2026-08-30: "Evaluating a string as JavaScript violates ... 'unsafe-eval' is not
an allowed source"). So the extension cannot evaluate a script the container sends; it can
only inject functions it already has, which chrome.scripting.executeScript serialises for
us with no eval involved.

That leaves one script in two places, which is the shape of bug this repo keeps paying for
(a rename that stops a sync, a doc that drifts from the code). So it is generated, not
copied: dom_snapshot.py stays the single source and this writes the extension's copy.

    python extension/build_probes.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "container" / "nanoagent"))

from nanoagent.agent.effector import dom_snapshot as ds  # noqa: E402

# _CONTENT_JS added 2026-09-06: the snapshot's other half — what the page SAYS, not
# just what can be clicked. Generated for the same reason as the element walk: one
# source in Python, no hand-copied twin that drifts.

OUT = Path(__file__).resolve().parent / "probes.generated.js"

BANNER = """// GENERATED by extension/build_probes.py — do not edit.
// Source of truth: container/nanoagent/nanoagent/agent/effector/dom_snapshot.py
//
// These are injected with chrome.scripting.executeScript({func}), which serialises the
// function. No eval, because MV3's CSP forbids it even in the isolated world — which is
// why the container names a probe instead of sending one.
"""


def main() -> None:
    body = [
        BANNER,
        f"export const INTERACTIVE_SELECTORS = {json.dumps(ds._INTERACTIVE_SELECTORS)};",
        "",
        f"export const MAX_FRAME_DEPTH = {ds._MAX_FRAME_DEPTH};",
        f"export const MIN_FRAME_PX = {ds._MIN_FRAME_PX};",
        "",
        "/** capture_dom_snapshot's element query, verbatim. Takes the selector list. */",
        f"export const snapshot = {ds._SNAPSHOT_JS.strip()};",
        "",
        "/** The page's readable text — headings, posts, list items. See dom_snapshot.py. */",
        f"export const pageContent = {ds._CONTENT_JS.strip()};",
        "",
    ]
    OUT.write_text("\n".join(body), encoding="utf-8")
    print(f"wrote {OUT.name}: {OUT.stat().st_size} bytes")


if __name__ == "__main__":
    main()
